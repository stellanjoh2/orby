/**
 * Build a self-hosted Font Awesome solid subset from icons used in the repo.
 * Scans HTML/JS/CSS, extracts matching rules from @fortawesome/fontawesome-free,
 * and subsets fa-solid-900.woff2.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'fs';
import { dirname, join, relative, resolve } from 'path';
import { fileURLToPath } from 'url';
import subsetFont from 'subset-font';
import * as esbuild from 'esbuild';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');
const faRoot = join(repoRoot, 'node_modules/@fortawesome/fontawesome-free');
const cssOut = join(repoRoot, 'styles/fontawesome/orby-icons.css');
const fontOut = join(repoRoot, 'assets/vendor/fontawesome/webfonts/fa-solid-900.woff2');
const manifestOut = join(repoRoot, 'styles/fontawesome/icons.json');

/** Not icon glyphs — FA style/utility class suffixes. */
