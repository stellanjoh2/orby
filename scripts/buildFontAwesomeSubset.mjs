  'beat',
  'bounce',
  'fade',
  'beat-fade',
  'flip',
  'shake',
  'spin',
  'spin-pulse',
  'spin-reverse',
  'pulse',
  'inverse',
  'stack',
  'stack-1x',
  'stack-2x',
  'rotate-90',
  'rotate-180',
  'rotate-270',
  'flip-horizontal',
  'flip-vertical',
  'flip-both',
  'rotate-by',
  '1x',
  '2x',
  '3x',
  '4x',
  '5x',
  '6x',
